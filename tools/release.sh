#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
: "${ANDROID_HOME:?ANDROID_HOME is required}"
: "${GITHUB_CLIENT_ID:?Public GitHub App Client ID is required}"
: "${GITHUBBLE_KEYSTORE:?Path to private release keystore is required}"
: "${GITHUBBLE_STORE_PASSWORD:?Keystore password is required}"
: "${GITHUBBLE_KEY_ALIAS:=githubble-release}"
GRADLE_BIN="${GRADLE_BIN:-gradle}"
BUILD_TOOLS="${ANDROID_HOME}/build-tools/36.0.0"
OUT="${ROOT}/release/out"
rm -rf "$OUT" && mkdir -p "$OUT"
cd "$ROOT"
"$GRADLE_BIN" --offline --no-daemon clean assembleRelease assembleDebugAndroidTest bundleRelease
"$ROOT/tools/generate-sbom.py" "$ROOT" "$OUT/GitHubble_1.0.0-rc1_SPDX.json"
"$BUILD_TOOLS/zipalign" -f 4 app/build/outputs/apk/release/app-release-unsigned.apk "$OUT/GitHubble_1.0.0-rc1-aligned.apk"
"$BUILD_TOOLS/apksigner" sign --ks "$GITHUBBLE_KEYSTORE" --ks-key-alias "$GITHUBBLE_KEY_ALIAS" --ks-pass "pass:$GITHUBBLE_STORE_PASSWORD" --key-pass "pass:$GITHUBBLE_STORE_PASSWORD" --out "$OUT/GitHubble_1.0.0-rc1.apk" "$OUT/GitHubble_1.0.0-rc1-aligned.apk"
cp app/build/outputs/bundle/release/app-release.aab "$OUT/GitHubble_1.0.0-rc1.aab"
jarsigner -keystore "$GITHUBBLE_KEYSTORE" -storepass "$GITHUBBLE_STORE_PASSWORD" -keypass "$GITHUBBLE_STORE_PASSWORD" "$OUT/GitHubble_1.0.0-rc1.aab" "$GITHUBBLE_KEY_ALIAS"
cp app/build/outputs/mapping/release/mapping.txt "$OUT/mapping.txt"
cp app/build/outputs/apk/androidTest/debug/app-debug-androidTest.apk "$OUT/GitHubble_1.0.0-rc1-instrumentation.apk"
"$BUILD_TOOLS/zipalign" -c -v 4 "$OUT/GitHubble_1.0.0-rc1.apk"
"$BUILD_TOOLS/apksigner" verify --verbose --print-certs "$OUT/GitHubble_1.0.0-rc1.apk"
sha256sum "$OUT"/* > "$OUT/SHA256SUMS.txt"
echo "Release output: $OUT"
